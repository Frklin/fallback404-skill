// The root not-found router: every 404 lands on the root not-found page, whose HTML is the same for every URL, so the
// section's design is chosen in the browser. NotFoundRouter (server) renders every design in a NotFoundGate; an inline
// script marks the design for this URL before the first paint, and CSS hides the others until React hydrates; then
// only the matching gate keeps its design. Spec: docs/superpowers/specs/2026-10-13-flow-steps-design.md (section 8.2).

const quote = (text) => `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

// How specific a route segment is, as the App Router ranks them: static, [x], [...x], [[...x]].
const segmentRank = (segment) => (segment.startsWith('[[...') ? 3 : segment.startsWith('[...') ? 2 : segment.startsWith('[') ? 1 : 0)

/** Sections ordered the way the App Router would match them: segment by segment, the more specific route first. */
export function bySpecificity(sections) {
  const ranks = (route) => route.split('/').filter(Boolean).map(segmentRank)
  return [...sections].sort((a, b) => {
    const left = ranks(a.route)
    const right = ranks(b.route)
    for (let i = 0; i < Math.max(left.length, right.length); i++) {
      // A route that ends here is more specific than one that goes on with a catch-all.
      const difference = (left[i] ?? -1) - (right[i] ?? -1)
      if (difference !== 0) return difference
    }
    return 0
  })
}

// The App Router's matching, shared by the generated gate and the inline script. Path segments are percent-decoded.
const MATCH_BODY = [
  "  const pattern = route.split('/').filter(Boolean)",
  "  const parts = path.split('/').filter(Boolean).map((part) => {",
  '    try {',
  '      return decodeURIComponent(part)',
  '    } catch {',
  '      return part',
  '    }',
  '  })',
  '  for (let i = 0; i < pattern.length; i++) {',
  "    if (pattern[i].startsWith('[[...')) return true",
  "    if (pattern[i].startsWith('[...')) return parts.length > i",
  "    if (i >= parts.length || (!pattern[i].startsWith('[') && pattern[i] !== parts[i])) return false",
  '  }',
  '  return pattern.length === parts.length',
]

/** The client half: route matching, the gate around each design, and the script that only the server HTML holds. */
export function renderGate({ typescript, basePath }) {
  const t = (type) => (typescript ? type : '')
  return [
    `'use client'`,
    '',
    `import { usePathname } from 'next/navigation'`,
    `import { useLayoutEffect, useState, useSyncExternalStore${typescript ? ', type ReactNode' : ''} } from 'react'`,
    '',
    '// Generated by write.mjs; do not edit. Before hydration every design is rendered and the CSS in NotFoundRouter',
    '// shows only the one the inline script picked; after hydration only the matching gate keeps its design.',
    ...(typescript ? ['type Section = { slug: string; route: string }', ''] : []),
    `const BASE_PATH = ${quote(basePath)}`,
    'const subscribe = () => () => {}',
    '',
    '/** True while React renders on the server or hydrates that HTML; false for every later client render. */',
    `const useHydrating = ()${t(': boolean')} => useSyncExternalStore(subscribe, () => false, () => true)`,
    '',
    '/**',
    ' * The URL path, or null until the first commit (server and hydration). Next.js writes the new URL during commit, after',
    ' * render, so it is read in a layout effect after every navigation: the matching design is in place before paint.',
    ' */',
    `function useBrowserPath()${t(': string | null')} {`,
    '  const navigation = usePathname()',
    `  const [path, setPath] = useState${t('<string | null>')}(null)`,
    '  useLayoutEffect(() => setPath(window.location.pathname), [navigation])',
    '  return path',
    '}',
    '',
    '/** True when a route such as /match/[id] or /docs/[...slug] matches the path; a trailing slash does not matter. */',
    `export function routeMatches(route${t(': string')}, path${t(': string')})${t(': boolean')} {`,
    ...MATCH_BODY,
    '}',
    '',
    '/** The slug of the first section whose route matches the path (basePath removed), else the root design. */',
    `export function sectionFor(sections${t(': readonly Section[]')}, root${t(': string')}, path${t(': string')}, basePath${t(': string')})${t(': string')} {`,
    "  const local = basePath !== '' && path.startsWith(basePath) ? path.slice(basePath.length) || '/' : path",
    '  return sections.find((section) => routeMatches(section.route, local))?.slug ?? root',
    '}',
    '',
    `export function NotFoundGate({ slug, root, sections, children }${t(': { slug: string; root: string; sections: readonly Section[]; children: ReactNode }')}) {`,
    '  const path = useBrowserPath()',
    '  if (path === null) return <div data-f404-flow={slug} data-f404-pending="">{children}</div>',
    '  return sectionFor(sections, root, path, BASE_PATH) === slug ? <div data-f404-flow={slug}>{children}</div> : null',
    '}',
    '',
    '/** The picking script, in the server HTML only: React never creates a script element on the client. */',
    `export function NotFoundScript({ code }${t(': { code: string }')}) {`,
    '  return useHydrating() ? <script dangerouslySetInnerHTML={{ __html: code }} /> : null',
    '}',
    '',
  ].join('\n')
}

/** The inline script: marks the router with the slug of this URL's design. ES5, no dependencies, data escaped for HTML. */
export function pickScript({ basePath, root, sections }) {
  const data = (value) => JSON.stringify(value).replace(/</g, '\\u003c')
  return [
    '(function(){',
    'var r=document.currentScript&&document.currentScript.parentNode;if(!r)return;',
    `var b=${data(basePath)},s=${data(sections)},p=location.pathname;`,
    "if(b&&p.indexOf(b)===0)p=p.slice(b.length)||'/';",
    "function d(x){try{return decodeURIComponent(x)}catch(e){return x}}",
    "function m(route,path){var a=route.split('/').filter(Boolean),q=path.split('/').filter(Boolean).map(d);",
    "for(var i=0;i<a.length;i++){if(a[i].indexOf('[[...')===0)return true;if(a[i].indexOf('[...')===0)return q.length>i;",
    "if(i>=q.length||(a[i].charAt(0)!=='['&&a[i]!==q[i]))return false}return a.length===q.length}",
    "for(var j=0;j<s.length;j++)if(m(s[j].route,p)){r.setAttribute('data-f404-show',s[j].slug);return}",
    `r.setAttribute('data-f404-show',${data(root)})`,
    '})()',
  ].join('')
}

/** Layout-neutral wrappers; while pending, every design but the picked one (or the root, without the script) is hidden. */
export function routerStyle(slugs, root) {
  const hide = (show) => `[data-f404-router][data-f404-show="${show}"]>[data-f404-pending]:not([data-f404-flow="${show}"])`
  return [
    '[data-f404-router],[data-f404-flow]{display:contents}',
    `[data-f404-router]:not([data-f404-show])>[data-f404-pending]:not([data-f404-flow="${root}"]),${slugs.map(hide).join(',')}{display:none}`,
  ].join('')
}

/** The server half: imports every not-found design and renders each in a gate, sections first (most specific first), the root last. */
export function renderRouter({ typescript, root, sections, spec, basePath = '' }) {
  const list = bySpecificity(sections).map(({ slug, route }) => ({ slug, route }))
  const slugs = [...list.map((section) => section.slug), root]
  const name = (slug) => `Flow${slugs.indexOf(slug)}`
  return [
    `import { NotFoundGate, NotFoundScript } from './NotFoundGate'`,
    ...slugs.map((slug) => `import { NotFound as ${name(slug)} } from '${spec(`flows/${slug}/NotFound`)}'`),
    '',
    '// Generated by write.mjs from .fallback404/plan.json; do not edit. Every 404 lands on the root not-found page:',
    "// this shows the design of the section the URL belongs to, without a flash (see NotFoundGate).",
    `const ROOT = ${quote(root)}`,
    `const SECTIONS = ${JSON.stringify(list)}${typescript ? ' as const' : ''}`,
    `const PICK = ${JSON.stringify(pickScript({ basePath, root, sections: list }))}`,
    `const STYLE = ${JSON.stringify(routerStyle(slugs, root))}`,
    '',
    'export function NotFoundRouter() {',
    '  return (',
    '    <div data-f404-router="" suppressHydrationWarning>',
    '      <NotFoundScript code={PICK} />',
    '      <style dangerouslySetInnerHTML={{ __html: STYLE }} />',
    ...slugs.map((slug) => [`      <NotFoundGate slug=${JSON.stringify(slug)} root={ROOT} sections={SECTIONS}>`, `        <${name(slug)} />`, '      </NotFoundGate>'].join('\n')),
    '    </div>',
    '  )',
    '}',
    '',
  ].join('\n')
}
